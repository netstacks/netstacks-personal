import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, fireEvent, act } from '@testing-library/react';

const env = vi.hoisted(() => ({ mode: 'enterprise' as 'standalone' | 'enterprise' }));
const http = {
  get: vi.fn(async () => ({ data: { has_main: false, params: [], has_inline_metadata: false } })),
  post: vi.fn(async () => ({ data: {} })),
  put: vi.fn(async () => ({ data: {} })),
  delete: vi.fn(async () => ({ data: null })),
};
vi.mock('../../api/client', () => ({
  getClient: () => ({ mode: env.mode, http }),
  getCurrentMode: () => env.mode,
  isClientInitialized: () => true,
}));
vi.mock('monaco-editor/esm/vs/editor/editor.api', () => ({ KeyMod: { CtrlCmd: 0 }, KeyCode: { KeyS: 0 } }));
vi.mock('@monaco-editor/react', () => ({
  default: ({ value, options }: { value: string; options: { readOnly?: boolean } }) => (
    <textarea data-testid="monaco" value={value} readOnly={options.readOnly} onChange={() => {}} />
  ),
}));
vi.mock('../../lsp/LspBridge', () => ({ LspBridge: () => null }));

import ScriptEditor from '../ScriptEditor';
import type { Script } from '../../api/scripts';
import { useCapabilitiesStore } from '../../stores/capabilitiesStore';

const base: Script = {
  id: 's1',
  name: 'collect',
  content: 'print(1)',
  last_run_at: null,
  created_at: '2026-01-01T00:00:00Z',
  updated_at: '2026-01-01T00:00:00Z',
};

function grant(permissions: string[]) {
  useCapabilitiesStore.setState({
    capabilities: { version: '1.0', license_tier: 'enterprise', features: [] },
    permissions,
  });
}

beforeEach(() => {
  env.mode = 'enterprise';
  http.put.mockClear();
  http.post.mockClear();
});

describe('ScriptEditor — Controller can_edit', () => {
  it('makes a script the user cannot edit read-only and never PUTs it', async () => {
    grant(['scripts.run']);
    render(<ScriptEditor script={{ ...base, shared: true, owner_name: 'alice', is_own: false, can_edit: false }} onSave={() => {}} tabId="t1" />);

    expect(screen.getByRole('status')).toHaveTextContent('Shared by alice — only its owner or an administrator can change it.');
    expect(screen.getByRole('button', { name: /Save/ })).toBeDisabled();
    expect(screen.getByTestId('monaco')).toHaveAttribute('readonly');
    expect(screen.getByPlaceholderText('Script name...')).toBeDisabled();

    // File → Save / Cmd+S on the tab is a no-op too.
    await act(async () => {
      window.dispatchEvent(new CustomEvent('netstacks:save-document', { detail: { tabId: 't1' } }));
    });
    expect(http.put).not.toHaveBeenCalled();
    // Running stays available.
    expect(screen.getByRole('button', { name: /Run/ })).toBeEnabled();
  });

  it('leaves an editable Controller script and a standalone script (no can_edit) editable', () => {
    grant(['scripts.run']);
    const { unmount } = render(<ScriptEditor script={{ ...base, is_own: true, can_edit: true }} onSave={() => {}} />);
    expect(screen.getByRole('button', { name: /Save/ })).toBeEnabled();
    expect(screen.queryByRole('status')).toBeNull();
    unmount();

    env.mode = 'standalone';
    grant(['*']);
    render(<ScriptEditor script={base} onSave={() => {}} />);
    expect(screen.getByRole('button', { name: /Save/ })).toBeEnabled();
    expect(screen.getByTestId('monaco')).not.toHaveAttribute('readonly');
  });
});

describe('ScriptEditor — AI-authored approval', () => {
  const aiScript: Script = { ...base, created_by: 'ai', approved: false, can_edit: true };

  it('shows the banner, and only a system.manage user may approve', () => {
    grant(['scripts.run']);
    const { unmount } = render(<ScriptEditor script={aiScript} onSave={() => {}} />);
    expect(screen.getByText('This script was generated by the AI.')).toBeInTheDocument();
    expect(screen.getByText(/An administrator must review and approve it/)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: /Approve to Run/ })).toBeDisabled();
    unmount();

    grant(['system.manage']);
    render(<ScriptEditor script={aiScript} onSave={() => {}} />);
    const approve = screen.getByRole('button', { name: /Approve to Run/ });
    expect(approve).toBeEnabled();
    fireEvent.click(approve);
    expect(http.post).toHaveBeenCalledWith('/scripts/s1/approve');
  });
});
